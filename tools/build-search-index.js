/* Builds assets/search-index.js from the pages themselves.

   Why a .js file and not .json: the site has to work from file://, and a
   fetch() or XHR for a local .json is blocked there by the same-origin rules.
   A <script src> is not. So the index assigns window.TLT_INDEX and the page
   loads it like any other script.

   Why a generated file at all: parsing fifteen pages at runtime would mean
   fetching them, which has the same problem, and doing it on every page load
   to serve one keystroke. The cost of generating is that it can go stale, so
   tests/search.test.js rebuilds it in memory and fails if it does not match
   what is committed.

   Run:  node tools/build-search-index.js
*/

const fs = require('fs');
const path = require('path');

const SITE = path.resolve(__dirname, '..');
const OUT = path.join(SITE, 'assets', 'search-index.js');

/* Text as a reader sees it: no tags, no entities, no raw TeX. The maths is
   deliberately dropped rather than transliterated -- "\frac{Z_L - Z_0}" is not
   something anyone types into a search box, and leaving it in would flood
   every snippet with backslashes. */
function plain(html){
  return html
    .replace(/<details[\s\S]*?<\/details>/gi, ' ')   /* track two is not indexed */
    .replace(/<script[\s\S]*?<\/script>/gi, ' ')
    .replace(/<style[\s\S]*?<\/style>/gi, ' ')
    .replace(/\$\$[\s\S]*?\$\$/g, ' ')
    .replace(/\\\[[\s\S]*?\\\]/g, ' ')
    .replace(/\$[^$\n]{1,200}\$/g, ' ')
    .replace(/\\\([\s\S]*?\\\)/g, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&middot;/g, '.').replace(/&mdash;/g, '-').replace(/&ndash;/g, '-')
    .replace(/&minus;/g, '-').replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"')
    .replace(/&[a-zA-Z]+\d*;/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function firstMatch(re, s){ const m = s.match(re); return m ? m[1] : ''; }

function build(){
  /* the report page is left out while site.js keeps it unlinked (REPORT_ON) */
  const reportOff = /var REPORT_ON = false;/.test(fs.readFileSync(path.join(SITE, 'assets', 'site.js'), 'utf8'));
  const pages = fs.readdirSync(SITE).filter(f => f.endsWith('.html'))
                  .filter(f => !(reportOff && f === 'report.html')).sort();
  const index = [];

  for (const file of pages){
    const html = fs.readFileSync(path.join(SITE, file), 'utf8');

    const rawTitle = firstMatch(/<title>([\s\S]*?)<\/title>/i, html);
    /* titles read "Reflection at a load &middot; Transmission Line Theory";
       the site name is in the masthead of every result already */
    const title = plain(rawTitle)
      .replace(/\s*[.·]\s*Transmission Line Theory\s*$/, '').trim() || file;
    /* the masthead carries "06 · Reflection at a load"; the number is worth
       having in the result list, so pull it out separately */
    const ch = plain(firstMatch(/<span class="ch">([\s\S]*?)<\/span>/i, html));
    const num = (ch.match(/^([0-9]{2}|P[12])\b/) || [, ''])[1];
    const lead = plain(firstMatch(/<p class="lead">([\s\S]*?)<\/p>/i, html)).slice(0, 260);

    const sections = [];
    /* Each <section class="blk" id="..."> up to the next one. The pages are
       written to one shape, which is what makes this safe; search.test.js
       checks the count so a page that stops following it cannot go unnoticed. */
    const re = /<section class="blk"(?:\s+id="([^"]*)")?[^>]*>([\s\S]*?)(?=<section class="blk"|<footer|<nav class="pager"|$)/gi;
    let m;
    while ((m = re.exec(html))){
      const id = m[1] || '';
      const body = m[2];
      const heading = plain(firstMatch(/<h2[^>]*>([\s\S]*?)<\/h2>/i, body));
      if (!heading) continue;
      const paras = [];
      const pre = /<p class="t"[^>]*>([\s\S]*?)<\/p>/gi;
      let pm;
      while ((pm = pre.exec(body)) && paras.join(' ').length < 760) paras.push(plain(pm[1]));
      sections.push({ h: heading, i: id, x: paras.join(' ').slice(0, 620) });
    }

    index.push({ p: file, t: title, n: num, l: lead, s: sections });
  }
  return index;
}

/* Pure ASCII, always. This file is served with no charset declaration, exactly
   like assets/site.js, so a literal non-ASCII byte in it turns into mojibake.
   The page text legitimately contains Greek and dashes, so rather than banning
   them they are escaped. One stray Gamma got through before this existed. */
function asciiOnly(s){
  return s.replace(/[\u0080-￿]/g, function(ch){
    return '\\u' + ('0000' + ch.charCodeAt(0).toString(16)).slice(-4);
  });
}

function serialise(index){
  const body = index.map(e => '  ' + JSON.stringify(e)).join(',\n');
  return '/* GENERATED by tools/build-search-index.js -- do not edit by hand.\n'
       + '   Rebuild with: node tools/build-search-index.js\n'
       + '   tests/search.test.js fails if this file is out of date. */\n'
       + 'window.TLT_INDEX = [\n' + asciiOnly(body) + '\n];\n';
}

if (require.main === module){
  const out = serialise(build());
  fs.writeFileSync(OUT, out);
  const n = build().reduce((a, e) => a + e.s.length, 0);
  console.log('wrote assets/search-index.js  ' + build().length + ' pages, ' +
              n + ' sections, ' + (out.length / 1024).toFixed(1) + ' KB');
}

module.exports = { build, serialise };
